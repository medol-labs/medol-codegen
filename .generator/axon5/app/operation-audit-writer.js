const {auditProcessingGroup, auditDeploymentName, hasLocalOperationAudit} = require('./axon-processing');
const {relatedEventsForSlice} = require('./model-helpers');
const {contextPackage} = require('../../common/util/value-types');
const {_commandTitle, _sliceTitle, _eventTitle} = require('../../common/util/naming');

function writeOperationAudit(generator, {packageName, context, slicePackage, slice, readmodel, name}) {
    const contract = generator.model.operationAudit;
    if (!contract || contract.context !== slice.context || contract.readModel !== readmodel.name) return;
    const expected = ['auditRecordId', 'occurredAt', 'completedAt', 'category', 'operation', 'outcome', 'actorId',
        'auditTenantId', 'messageId', 'correlationId', 'targetId', 'durationMs', 'errorCode', 'httpStatus'];
    if (expected.some(field => !(readmodel.fields ?? []).some(candidate => candidate.name === field))) {
        throw new Error('Operation audit catalog is missing required infrastructure fields.');
    }
    const targets = (generator.model.slices ?? []).flatMap(owner => (owner.commands ?? []).flatMap(command => {
        const ids = (command.fields ?? []).filter(field => field.idAttribute && field.cardinality !== 'Multiple');
        if (!ids.length) return [];
        const type = `${generator.model.rootPackage}.${contextPackage(owner.context)}.${_sliceTitle(owner.title ?? owner.name)}.${_commandTitle(command.title ?? command.name)}`;
        return [`        is ${type} -> listOf(${ids.map(field => `payload.${field.name}?.toString()`).join(', ')}).filterNotNull().joinToString(",").take(255)`];
    })).join('\n');
    // Axon 5 resolves exact event names; an Any/Object handler is NOT a catch-all.
    const businessTypes = [...new Set((generator.model.slices ?? []).filter(owner => owner.commands?.length || (generator.model.numbering && owner.context === generator.model.numbering.context)).flatMap(owner =>
        relatedEventsForSlice(generator.model, owner).map(event => {
            const eventOwner = generator.model.slices.find(candidate => candidate.title === event.slice || candidate.name === event.slice) ?? owner;
            return `${generator.model.rootPackage}.${contextPackage(eventOwner.context)}.events.${_eventTitle(event.title ?? event.name)}`;
        })))];
    const archiving = require('./archiving-writer').localArchiving(generator);
    if (archiving) businessTypes.push(`${generator.model.rootPackage}.archiving.infrastructure.ArchiveOperationRecorded`);
    const businessHandlers = businessTypes.map((type, index) => `    @EventHandler
    fun onBusiness${index}(event: ${type}, message: EventMessage) = on(event, message)`).join('\n\n');
    const options = {
        rootPackage: generator.model.rootPackage, packageName, readModelName: name,
        tenancy: Boolean(generator.model.tenancy), archiving, targets, businessHandlers,
        deployment: auditDeploymentName(generator), processingGroup: auditProcessingGroup(generator)
    };
    for (const file of ['OperationAuditSupport', 'AuditTrailProjection']) {
        generator.fs.copyTpl(generator.templatePath(`operation-audit/${file}.kt.tpl`),
            generator._kotlinPath(`${context}/${slicePackage}/${file}.kt`), options);
    }
}
function cleanupOperationAudit(generator) {
    if (hasLocalOperationAudit(generator.model)) return;
    // These are infrastructure sources owned by the builtin; do not delete user-authored classes.
    for (const file of ['OperationAuditSupport', 'AuditTrailProjection']) {
        const target = generator._kotlinPath(`operationaudit/operationauditcatalog/${file}.kt`);
        if (!generator.fs.exists(target)) continue;
        const source = generator.fs.read(target);
        const owned = source.startsWith('// Generated by MEDOL operation-audit.')
            || (file === 'OperationAuditSupport' && source.includes('medol.audit.httpState')
                && /class OperationAudit(Publisher|Recorder)/.test(source))
            || (file === 'AuditTrailProjection' && source.includes('event is OperationExecutionRecorded')
                && source.includes('class AuditTrailProjection'));
        if (owned) generator.fs.delete(target);
    }
}
module.exports = {writeOperationAudit, cleanupOperationAudit};
