function renderHarborInstallScript() {
    return `#!/usr/bin/env node

import {copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync} from 'node:fs';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';

const scriptDir = dirname(fileURLToPath(import.meta.url));
loadDotEnv(resolve(scriptDir, '.env'));

const installer = resolve(scriptDir, process.env.HARBOR_INSTALLER ?? '');
const workDir = resolve(scriptDir, '.work');
const extractDir = resolve(workDir, 'installer');
const configTemplate = resolve(scriptDir, 'harbor.yml-example');
const renderedConfig = resolve(scriptDir, 'harbor.yml');

if (!process.env.HARBOR_INSTALLER) {
    fail('Set HARBOR_INSTALLER in .env or the environment. Use the Harbor offline installer tarball.');
}
if (!existsSync(installer)) {
    fail(\`Harbor installer was not found: \${installer}\`);
}
if (!existsSync(configTemplate)) {
    fail(\`Harbor config template was not found: \${configTemplate}\`);
}

mkdirSync(workDir, {recursive: true});
rmSync(extractDir, {recursive: true, force: true});
mkdirSync(extractDir, {recursive: true});
renderTemplate(configTemplate, renderedConfig);

run('tar', ['-xzf', installer, '-C', extractDir]);

const harborDir = resolve(extractDir, 'harbor');
if (!existsSync(harborDir)) {
    fail(\`Expected extracted Harbor directory was not found: \${harborDir}\`);
}

copyFileSync(renderedConfig, resolve(harborDir, 'harbor.yml'));
run('./install.sh', [], harborDir);

console.log('[harbor] installed. Use docker compose in the extracted Harbor directory for lifecycle operations.');

function renderTemplate(source, target) {
    const text = readFileSync(source, 'utf8').replace(/\\$\\{([A-Z0-9_]+)(:-([^}]*))?}/g, (_, name, _fallbackExpression, fallback) =>
        process.env[name] ?? fallback ?? ''
    );
    writeFileSync(target, text);
}

function loadDotEnv(path) {
    if (!existsSync(path)) return;
    const lines = readFileSync(path, 'utf8').split(/\\r?\\n/);
    for (const line of lines) {
        const trimmed = line.trim();
        if (!trimmed || trimmed.startsWith('#') || !trimmed.includes('=')) continue;
        const index = trimmed.indexOf('=');
        const key = trimmed.slice(0, index).trim();
        const value = trimmed.slice(index + 1).trim().replace(/^['"]|['"]$/g, '');
        if (key && process.env[key] === undefined) {
            process.env[key] = value;
        }
    }
}

function run(command, args, cwd = scriptDir) {
    console.log(\`[harbor] $\{command} $\{args.join(' ')}\`);
    const result = spawnSync(command, args, {cwd, stdio: 'inherit'});
    if (result.status !== 0) {
        process.exit(result.status ?? 1);
    }
}

function fail(message) {
    console.error(\`[harbor] \${message}\`);
    process.exit(1);
}
`;
}

function zotFiles(model, environment, options = {}) {
    const root = options.root ?? `${environmentDirectory(environment)}/zot`;
    const hostname = `${model.name}-zot.local`;
    return {
        [`${root}/README.md`]: renderZotReadme(model, environment, hostname),
        [`${root}/.env-example`]: renderZotEnvExample(hostname),
        [`${root}/docker-compose.yml`]: renderZotDockerCompose(),
        [`${root}/config.json`]: renderZotConfig()
    };
}

function renderZotReadme(model, environment, hostname) {
    return [
        '# zot operations',
        '',
        `Optional zot OCI registry operations assets for ${model.title} (${environment}).`,
        '',
        'zot is the recommended lightweight registry for ARM64 and offline LAN deployments. The official container image is multi-architecture, so Docker or containerd selects the host architecture automatically unless you explicitly pull another platform.',
        '',
        '## Start',
        '',
        '```bash',
        'cp .env-example .env',
        'docker compose up -d',
        '```',
        '',
        'The registry listens on `ZOT_HTTP_PORT` and stores blobs under the `zot-data` volume.',
        '',
        '## Offline image package',
        '',
        'On a connected machine, pull and save the image for the target architecture:',
        '',
        '```bash',
        'docker pull --platform linux/arm64 ghcr.io/project-zot/zot:v2.1.20',
        'docker save ghcr.io/project-zot/zot:v2.1.20 -o zot-linux-arm64-v2.1.20.tar',
        '```',
        '',
        'Load it on the offline host:',
        '',
        '```bash',
        'docker load -i zot-linux-arm64-v2.1.20.tar',
        '```',
        '',
        '## Application image naming',
        '',
        'Use this registry as the generated operations image prefix, for example:',
        '',
        '```text',
        `${hostname}:5000/${model.name}/<service>:<tag>`,
        '```',
        '',
        'For plain HTTP LAN deployments, configure Docker/containerd on each node to trust the registry as an insecure registry.',
        ''
    ].join('\n');
}

function renderZotEnvExample(hostname) {
    return [
        'ZOT_IMAGE=ghcr.io/project-zot/zot:v2.1.20',
        `ZOT_HOSTNAME=${hostname}`,
        'ZOT_HTTP_PORT=5000',
        ''
    ].join('\n');
}

function renderZotDockerCompose() {
    return [
        'services:',
        '  zot:',
        '    image: ${ZOT_IMAGE:-ghcr.io/project-zot/zot:v2.1.20}',
        '    restart: unless-stopped',
        '    ports:',
        '      - "${ZOT_HTTP_PORT:-5000}:5000"',
        '    volumes:',
        '      - ./config.json:/etc/zot/config.json:ro',
        '      - zot-data:/var/lib/registry',
        '    command:',
        '      - serve',
        '      - /etc/zot/config.json',
        '',
        'volumes:',
        '  zot-data:',
        ''
    ].join('\n');
}

function renderZotConfig() {
    return `${JSON.stringify({
        distSpecVersion: '1.1.0',
        storage: {
            rootDirectory: '/var/lib/registry'
        },
        http: {
            address: '0.0.0.0',
            port: '5000',
            compat: [
                'docker2s2'
            ]
        },
        log: {
            level: 'info'
        }
    }, null, 2)}\n`;
}

