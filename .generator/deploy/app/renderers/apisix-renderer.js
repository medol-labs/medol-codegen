const { renderYaml } = require('./yaml');

function renderApisixConfig(model) {
    const gateway = requireGateway(model);
    return renderYaml({
        apisix: {
            node_listen: gateway.servicePort,
            enable_admin: false
        },
        deployment: {
            role: 'data_plane',
            role_data_plane: {
                config_provider: 'yaml'
            }
        }
    });
}

function renderApisixStandaloneConfig(model) {
    const gateway = requireGateway(model);
    const routes = gateway.routes.map((route) => ({
        id: route.id,
        name: route.name,
        uri: route.paths[0],
        ...(route.methods?.length ? { methods: route.methods } : {}),
        upstream_id: route.upstreamId,
        ...(route.plugins?.length ? { plugins: pluginsToObject(route.plugins) } : {})
    }));
    const upstreams = gateway.upstreams.map((upstream) => ({
        id: upstream.id,
        type: 'roundrobin',
        nodes: {
            [`${upstream.serviceName}:${upstream.servicePort}`]: 1
        }
    }));

    return `${renderYaml({
        routes,
        upstreams,
        ...(gateway.plugins?.length ? { global_rules: [{
            id: 'gateway-global-plugins',
            plugins: pluginsToObject(gateway.plugins)
        }] } : {})
    }).trimEnd()}\n#END\n`;
}

function renderApisixReadme() {
    return [
        '# APISIX Gateway',
        '',
        'Generated by the Medol deploy generator.',
        '',
        '- `config.yaml` runs APISIX in standalone YAML mode.',
        '- `apisix.yaml` contains generated routes and upstreams.',
        '- Do not edit generated files directly. Add manual gateway rules through a future overlay file or regenerate from the model.',
        ''
    ].join('\n');
}

function apisixFiles(model, options = {}) {
    const root = trimRoot(options.root ?? 'infrastructure/apisix');
    return {
        [`${root}/config.yaml`]: renderApisixConfig(model),
        [`${root}/apisix.yaml`]: renderApisixStandaloneConfig(model),
        [`${root}/README.md`]: renderApisixReadme()
    };
}

function trimRoot(value) {
    return String(value ?? '').replace(/^\/+|\/+$/g, '') || '.';
}

function pluginsToObject(plugins = []) {
    return Object.fromEntries(plugins.map((plugin) => [
        plugin.name,
        plugin.configuration ?? {}
    ]));
}

function requireGateway(model) {
    if (!model.gateway?.enabled) {
        throw new Error('APISIX gateway is not enabled in the deployment model.');
    }
    return model.gateway;
}

module.exports = {
    apisixFiles,
    renderApisixConfig,
    renderApisixStandaloneConfig
};
