import {execFileSync} from 'node:child_process';
import {mkdtempSync, mkdirSync, readFileSync, writeFileSync, copyFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url));
const repo=path.resolve(here,'../../../..');
const medol=process.env.MEDOL_SOURCE_ROOT ?? path.resolve(repo,'../medol');
const workspace=mkdtempSync(path.join(tmpdir(),'medol-scheduling-'));
const source=path.join(workspace,'source.medol');
copyFileSync(path.join(here,'fixtures/scheduling/source.medol'),source);
const json=execFileSync(process.execPath,['--import',path.join(medol,'node_modules/tsx/dist/loader.mjs'),path.join(medol,'src/lib/dslToCodegenModelCli.ts'),source],{encoding:'utf8'});
writeFileSync(path.join(workspace,'codegen-model.json'),json);
execFileSync(process.execPath,[path.join(repo,'gen.sh'),path.join(repo,'.generator/axon5/app'),'--generator-type','all','--output-root','axon5','--force','--skip-install'],{cwd:workspace,stdio:'inherit',env:{...process.env,CODEGEN_DEPLOYMENT:'',CODEGEN_DOMAIN:''}});
const target=path.join(workspace,'axon5/src/test/kotlin/tech/medo/scheduling/infrastructure');
mkdirSync(target,{recursive:true});
copyFileSync(path.join(here,'fixtures/scheduling/SchedulingRuntimeTest.kt'),path.join(target,'SchedulingRuntimeTest.kt'));
console.log(`Scheduling runtime fixture: ${workspace}`);
execFileSync(process.env.MAVEN_BIN ?? 'mvn',['-q','-Dtest=SchedulingRuntimeTest','-Dsurefire.failIfNoSpecifiedTests=false','-Dkotlin.compiler.daemon=false','test'],{cwd:path.join(workspace,'axon5'),stdio:'inherit'});
