const { apisixFiles } = require('./renderers/apisix-renderer');
const { dockerComposeFiles } = require('./renderers/docker-compose-renderer');
const { k3sFiles, kubernetesFiles } = require('./renderers/kubernetes-renderer');

const targets = ['all', 'model', 'apisix', 'docker-compose', 'kubernetes', 'k3s', 'harbor', 'zot'];

function generateOperationsFiles(model, options = {}) {
    const target = options.target ?? 'all';
    const environment = options.environment ?? 'dev';
    const environmentRoot = environmentDirectory(environment);
    const files = {
        [`${environmentRoot}/operations-model.json`]: `${JSON.stringify(model, null, 2)}\n`,
        [`${environmentRoot}/README.md`]: renderDeployReadme(model, environment)
    };

    if (target === 'model') return files;
    if (target === 'all' || target === 'apisix' || target === 'docker-compose' || target === 'kubernetes' || target === 'k3s') {
        Object.assign(files, apisixFiles(model, {
            root: `${environmentRoot}/infrastructure/apisix`
        }));
    }
    if (target === 'all' || target === 'docker-compose') {
        Object.assign(files, dockerComposeFiles(model, environment, {
            root: environmentRoot
        }));
    }
    if (target === 'all' || target === 'kubernetes') {
        Object.assign(files, kubernetesFiles(model, {
            environmentName: environment,
            root: `${environmentRoot}/kubernetes`
        }));
    }
    if (target === 'all' || target === 'k3s') {
        Object.assign(files, k3sFiles(model, {
            environmentName: environment,
            root: `${environmentRoot}/k3s`
        }));
    }
    if (target === 'all' || target === 'harbor') {
        Object.assign(files, harborFiles(model, environment, {
            root: `${environmentRoot}/harbor`
        }));
    }
    if (target === 'all' || target === 'zot') {
        Object.assign(files, zotFiles(model, environment, {
            root: `${environmentRoot}/zot`
        }));
    }

    return files;
}

function renderDeployReadme(model, environment) {
    const applications = model.applications
        .map((application) => `- ${application.name} (${application.kind}, port ${application.servicePort})`)
        .join('\n');
    const infrastructure = model.infrastructure
        .map((component) => `- ${component.name} (${component.type}${component.enabled === false ? ', optional/profiled' : ''})`)
        .join('\n');
    const routes = (model.gateway?.routes ?? [])
        .map((route) => `- ${route.paths.join(', ')} -> ${route.upstreamId}`)
        .join('\n');

    return [
        '# Medol operations artifacts',
        '',
        `Generated by the Medol operations generator for the ${environment} environment. These files describe runtime topology only; they do not provision clusters or execute remote operations.`,
        '',
        '## Applications',
        '',
        applications || '- none',
        '',
        '## Infrastructure',
        '',
        infrastructure || '- none',
        '',
        '## Gateway Routes',
        '',
        routes || '- APISIX gateway disabled',
        '',
        '## Flow',
        '',
        '```text',
        'CodegenModel',
        '  -> DeploymentModelBuilder',
        '  -> EnvironmentResolver',
        '  -> Docker Compose / Kubernetes / K3s / APISIX renderers',
        '```',
        '',
        '## Not Implemented',
        '',
        '- Terraform',
        '- GitOps controllers',
        '- Secret manager integration',
        '- Cluster provisioning',
        '- APISIX Ingress Controller',
        '- Kubernetes Gateway API',
        '- Autoscaling',
        ''
    ].join('\n');
}

function environmentDirectory(environment) {
    const name = String(environment ?? 'dev')
        .trim()
        .toLowerCase()
        .replace(/[^a-z0-9_-]+/g, '-')
        .replace(/^-+|-+$/g, '') || 'dev';
    return `operations/${name}`;
}

function harborFiles(model, environment, options = {}) {
    const root = options.root ?? `${environmentDirectory(environment)}/harbor`;
    const hostname = `${model.name}-harbor.local`;
    return {
        [`${root}/README.md`]: renderHarborReadme(model, environment),
        [`${root}/.env-example`]: renderHarborEnvExample(hostname),
        [`${root}/harbor.yml-example`]: renderHarborConfig(hostname),
        [`${root}/install-harbor.mjs`]: renderHarborInstallScript()
    };
}

